#!/usr/bin/env python3
"""Generate fields.lua from the SAMPFUNCS SFAPI per-version headers.

The scanner finds *pointers*; this gives you the *members* behind them. The SFAPI
headers ship one SFSAMP.h per build, and the layouts genuinely differ between
builds, so these offsets must never be hardcoded from a single version.

Usage:
    ./gen_fields.py [--sdk <SFAPI/samp dir>] [-o <fields.lua>] [struct ...]

Default structs are stSAMP and stSAMPPools. Anything whose field types this
script does not know about is a hard error, never a silent guess -- a wrong
offset here writes to the wrong memory.

Everything emitted was cross-checked against the four reference DLLs; see
README.md for the evidence (most-dereferenced field == `pools` on every build,
ctor stores matching serverIp/serverPort/rakClientInterface).
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

DEFAULT_SDK = '/mnt/data/Projects/New Folder/cmake-sf-plugin/lib/SFAPI/samp'

# SFAPI directory -> the version tag this repo uses (fixes.lua, version.lua)
VERSION_DIRS = [
    ('v0.3.7-R1',   'R1'),
    ('v0.3.7-R3-1', 'R3'),      # the 'R3' tag is the R3-1 build
    ('v0.3.7-R5',   'R5'),
    ('v0.3.DL',     'DLR1'),
]

# Sizes under #pragma pack(1). Pointers are all 4 bytes: samp.dll is 32-bit.
SIZES = {
    'void*': 4, 'char': 1, 'uint8_t': 1, 'int8_t': 1, 'bool': 1,
    'uint16_t': 2, 'int16_t': 2, 'short': 2,
    'int': 4, 'uint32_t': 4, 'int32_t': 4, 'BOOL': 4, 'DWORD': 4, 'float': 4,
    'Gamestate': 4, 'PlayerState': 1, 'UpdateType': 1,
}

KIND = {
    'bool': 'bool', 'char': 'char', 'uint8_t': 'u8', 'int8_t': 'i8',
    'uint16_t': 'u16', 'int16_t': 'i16', 'short': 'i16',
    'int': 'i32', 'int32_t': 'i32', 'uint32_t': 'u32', 'BOOL': 'i32',
    'DWORD': 'u32', 'float': 'float', 'Gamestate': 'i32',
    'PlayerState': 'u8', 'UpdateType': 'u8',
}


def enum_constants(src: str) -> dict:
    """Collect `NAME = 123` pairs from enums, for array bounds."""
    out = {}
    for body in re.findall(r'enum\s+\w+[^{]*\{(.*?)\}', src, re.S):
        for name, value in re.findall(r'(\w+)\s*=\s*(\d+)', body):
            out[name] = int(value)
    return out


def parse_struct(src: str, struct: str, consts: dict, path: str):
    m = re.search(r'struct\s+(?:SAMPFUNCS_API\s+)?' + re.escape(struct) + r'\s*\{(.*?)\n\};',
                  src, re.S)
    if not m:
        raise SystemExit(f'{path}: struct {struct} not found')

    offset, fields = 0, []
    for raw in m.group(1).splitlines():
        line = raw.split('//')[0].strip().rstrip(';').strip()
        if not line or '(' in line:          # blank, comment, or a method
            continue
        line = re.sub(r'^(struct|class|enum)\s+', '', line)
        fm = re.match(r'([\w:]+\s*\*?)\s*(\w+)\s*(?:\[\s*(\w+)\s*\])?$', line)
        if not fm:
            raise SystemExit(f'{path}: cannot parse field {line!r} of {struct}')
        ctype = fm.group(1).replace(' ', '')
        name, bound = fm.group(2), fm.group(3)

        count = 1
        if bound is not None:
            count = consts.get(bound, None)
            if count is None:
                if not bound.isdigit():
                    raise SystemExit(f'{path}: unknown array bound {bound!r} in {struct}.{name}')
                count = int(bound)

        if ctype.endswith('*'):
            size, kind = 4, 'ptr'
        else:
            if ctype not in SIZES:
                raise SystemExit(f'{path}: unknown type {ctype!r} in {struct}.{name}')
            size, kind = SIZES[ctype], KIND[ctype]

        if count > 1 and kind == 'char':
            kind = 'str'

        fields.append({'name': name, 'offset': offset, 'kind': kind,
                       'count': count, 'size': size * count, 'ctype': ctype})
        offset += size * count

    return fields, offset


def emit(structs: dict, sdk: str) -> str:
    out = [
        '-- signature_scanner/fields.lua',
        '--',
        '-- GENERATED by tools/gen_fields.py from the SAMPFUNCS SFAPI headers.',
        '-- Do not edit by hand; re-run the generator instead.',
        f'--   source: {sdk}',
        '--',
        '-- The scanner resolves *pointers*; this file describes the *members* behind',
        '-- them. Offsets are per build because the layouts really do differ -- see the',
        '-- warnings below. Cross-checked against the four reference DLLs (README.md).',
        '--',
        '--   local fields = require("signature_scanner.fields")',
        '--   local off = fields.offset("stSAMP", "pools", sig.detected.version)',
        '--   local pools = sig.memory.readU32(sig.resolve("CNetGame") and ... + off)',
        '',
        'local M = {}',
        '',
    ]

    for struct, per_version in structs.items():
        # Flag any field whose offset is not the same on every build.
        tags = [tag for _, tag in VERSION_DIRS]
        varying = []
        names = [f['name'] for f in per_version[tags[0]]['fields']]
        for n in names:
            offs = {}
            for t in tags:
                match = next((f for f in per_version[t]['fields'] if f['name'] == n), None)
                if match:
                    offs[t] = match['offset']
            if len(set(offs.values())) > 1:
                varying.append((n, offs))

        out.append('--' + '-' * 78)
        out.append(f'-- {struct}')
        out.append('--' + '-' * 78)
        sizes = {t: per_version[t]['size'] for t in tags}
        out.append('-- sizeof: ' + ', '.join(f'{t}=0x{s:X}' for t, s in sizes.items()))
        if varying:
            out.append('--')
            out.append('-- WARNING -- these members move between builds. Never hardcode them from')
            out.append('-- one version; always look them up with the running build\'s tag:')
            for n, offs in varying:
                out.append('--   ' + f'{n:<20}' + ' '.join(f'{t}=+0x{o:X}' for t, o in offs.items()))
        out.append('')

        out.append(f'M.{struct} = {{')
        for tag in tags:
            info = per_version[tag]
            out.append(f'    {tag} = {{')
            out.append(f'        _size = 0x{info["size"]:X},')
            for f in info['fields']:
                extra = f', count = {f["count"]}' if f['count'] > 1 else ''
                out.append(f'        {f["name"]} = {{ offset = 0x{f["offset"]:X}, '
                           f'kind = {f["kind"]!r}{extra} }},  -- {f["ctype"]}')
            out.append('    },')
        out.append('}')
        out.append('')

    out += [
        '-- Offset of a member for a given build, or nil when that build has no such',
        '-- member (R1\'s stSAMP genuinely lacks fields the later ones have).',
        'function M.offset(struct, field, version)',
        '    local s = M[struct]; if not s then return nil end',
        '    local v = version and s[version]; if not v then return nil end',
        '    local f = v[field]',
        '    return f and f.offset or nil',
        'end',
        '',
        'function M.field(struct, field, version)',
        '    local s = M[struct]; if not s then return nil end',
        '    local v = version and s[version]; if not v then return nil end',
        '    return v[field]',
        'end',
        '',
        'function M.layout(struct, version)',
        '    local s = M[struct]; if not s then return nil end',
        '    return version and s[version] or nil',
        'end',
        '',
        'return M',
        '',
    ]
    return '\n'.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('structs', nargs='*', default=['stSAMP', 'stSAMPPools'])
    ap.add_argument('--sdk', default=DEFAULT_SDK)
    ap.add_argument('-o', '--output')
    args = ap.parse_args(argv)

    sdk = pathlib.Path(args.sdk)
    parsed = {}
    for struct in args.structs:
        parsed[struct] = {}
        for directory, tag in VERSION_DIRS:
            path = sdk / directory / 'SFSAMP.h'
            if not path.exists():
                raise SystemExit(f'missing {path}')
            src = path.read_text(errors='replace')
            fields, size = parse_struct(src, struct, enum_constants(src), str(path))
            parsed[struct][tag] = {'fields': fields, 'size': size}

    text = emit(parsed, str(sdk))
    if args.output:
        pathlib.Path(args.output).write_text(text)
        print(f'wrote {args.output}')
    else:
        sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
